// Окно «оседания результата» перед заморозкой. «Завершено» ≠ «окончательно»:
// у команд ~36ч на апелляцию (FIA) + у FIA ~36ч на вердикты по отложенным
// нарушениям, плюс возможное расследование. Поэтому после финиша сессии ещё
// какое-то время ТЯНЕМ результат каждый прогон (штраф/апелляция подхватятся,
// writeIfChanged закоммитит только при реальном изменении), и лишь по истечении
// окна — freeze (не рескрейпим).
//
// Окон два, и разводит их не осторожность, а ПРЕДМЕТ наблюдения:
//
//   Результат (классификация, времена сессий, зеркала) — 7 дней. Апелляция 36ч
//   + вердикты 36ч (72ч) с запасом на расследование; дальше протокол уже
//   окончателен, тянуть его каждый час нечего, а источник — это нагрузка.
//
//   Решения стюардов (штрафные документы) — 14 дней. Право FIA на пересмотр
//   живёт две недели, и вердикт по протесту выходит на 8–10-й день. В недельное
//   окно он не попадал и терялся НАВСЕГДА: после заморозки раунд не
//   перечитывается никогда. Вторая неделя почти ничего не стоит — прогон
//   докачивает только те документы, которых в файле ещё нет (fia.ts).
//
// Длинное окно — привилегия продьюсера, чей файл НАКАПЛИВАЕТСЯ (mergeFiaEvent):
// там неудачный прогон ничего не стирает — удалений в нём нет вовсе, пропажа
// документа со страницы только логируется. Продьюсеру, который перезаписывает
// файл тем, что наскрёб за прогон, второе окно ПРОТИВОПОКАЗАНО — оно вдвое
// удлиняет период, в котором одна осечка затирает собранное. Так сейчас живут
// wecfia.ts и imsafia.ts: они остаются на isFrozen до переноса слияния.

const DAY_MS = 24 * 3600 * 1000;

/// Результаты: 7 дней — апелляция 36ч + вердикты 36ч (72ч) с запасом.
export const FREEZE_AFTER_MS = 7 * DAY_MS;

/// Решения стюардов: 14 дней — срок права FIA на пересмотр.
export const STEWARDS_FREEZE_AFTER_MS = 14 * DAY_MS;

const settled = (finishMs: number | null, now: number, windowMs: number): boolean =>
  finishMs !== null && !Number.isNaN(finishMs) && now - finishMs > windowMs;

/// finishMs — момент финиша (ISO-инстант последней сессии/дня гонки), now — Date.now().
/// true → результат «оседал» дольше окна → можно морозить.
export function isFrozen(finishMs: number | null, now: number): boolean {
  return settled(finishMs, now, FREEZE_AFTER_MS);
}

/// То же для решений стюардов — вдвое длиннее. Отдельная ФУНКЦИЯ, а не параметр
/// окна у isFrozen: параметр уезжает в соседний продьюсер вместе со скопированной
/// строкой вызова и молча удлиняет ему окно, а имя приходится менять осознанно.
/// Кто на длинном окне — считает не grep (имя намеренно упомянуто в коммента-
/// риях wecfia/imsafia, у которых окно ОБЫЧНОЕ), а сторож в freeze.test.ts:
/// он выкидывает комментарии и сверяет вызовы с белым списком продьюсеров.
export function isStewardsFrozen(finishMs: number | null, now: number): boolean {
  return settled(finishMs, now, STEWARDS_FREEZE_AFTER_MS);
}
